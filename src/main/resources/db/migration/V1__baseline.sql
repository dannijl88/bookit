-- Baseline del esquema actual de Bookit/Slotlyfy.
-- Generado con el export de DDL real de Hibernate (jakarta.persistence.schema-generation)
-- contra un PostgreSQL 17 vacío, de modo que reproducing exactamente lo que
-- ddl-auto=update/create ha creado hasta ahora en Neon y en local.
--
-- IMPORTANTE: en la base de la demo (Neon) estas tablas YA EXISTEN.
-- Por eso la app configura Flyway con baseline-on-migrate=true y baseline-version=1:
-- sobre un esquema no vacío sin historial, Flyway marca la versión 1 como aplicada
-- sin ejecutar este fichero, y solo correrá V2 en adelante.
-- En una base vacía (tests, nuevos entornos) Flyway sí ejecuta V1 normalmente.

create table appointments (
    active_slot timestamp GENERATED ALWAYS AS (CASE WHEN status <> 'CANCELLED' THEN appointment_datetime ELSE NULL END) STORED,
    appointment_datetime timestamp(6) not null,
    client_id bigint,
    employee_id bigint,
    id bigint generated by default as identity,
    service_id bigint,
    status varchar(255) check ((status in ('PENDING','CONFIRMED','CANCELLED','COMPLETED'))),
    primary key (id),
    constraint uk_employee_active_slot unique (employee_id, active_slot)
);

create table business (
    active boolean not null,
    id bigint generated by default as identity,
    owner_id bigint,
    address varchar(255) not null,
    category varchar(255) not null,
    name varchar(255) not null,
    opening_hours varchar(255) not null,
    phone varchar(255) not null,
    primary key (id)
);

create table employees (
    active boolean not null,
    id bigint generated by default as identity,
    business_id bigint,
    name varchar(255) not null,
    primary key (id)
);

create table employee_schedule (
    end_time time(0) not null,
    start_time time(0) not null,
    employee_id bigint not null,
    id bigint generated by default as identity,
    day_of_week varchar(255) not null check ((day_of_week in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
    primary key (id)
);

create table reviews (
    rating integer not null check ((rating>=1) and (rating<=5)),
    appointment_id bigint unique,
    id bigint generated by default as identity,
    comment varchar(255),
    primary key (id)
);

create table services (
    active boolean not null,
    duration integer not null check ((duration>=30)),
    price float(53) not null,
    business_id bigint not null,
    id bigint generated by default as identity,
    description varchar(255) not null,
    name varchar(255) not null,
    primary key (id)
);

create table users (
    id bigint generated by default as identity,
    email varchar(255) not null unique,
    name varchar(255) not null,
    password varchar(255) not null,
    phone varchar(255) not null,
    role varchar(255) check ((role in ('ADMIN','BUSINESS_OWNER','CLIENT'))),
    primary key (id)
);

